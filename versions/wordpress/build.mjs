// Source remains modular and reviewable. Only the output PHP file is installed.
function phpBody(source, label) {
  const match = source.match(
    /^<\?php\s*(?:declare\(strict_types=1\);\s*)?namespace (?:Governance|AiGovernanceWP);\s*/,
  );
  if (!match) throw new Error(`Unexpected namespace/header in ${label}`);
  return source.slice(match[0].length).trim();
}

